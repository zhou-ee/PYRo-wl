struct Coefficients {
    float gamma[42], position_gain[42], velocity_gain[42];
    float step_position_gain[42], step_velocity_gain[42];
    float step_poles[6], step_input_gain[6];
};
static_assert(sizeof(Coefficients) == 222*sizeof(float), "coefficient layout");
inline float evaluate_gamma(const float c[4][4], float x1, float x2) {
    const float r0=((c[0][3]*x2+c[0][2])*x2+c[0][1])*x2+c[0][0];
    const float r1=((c[1][3]*x2+c[1][2])*x2+c[1][1])*x2+c[1][0];
    const float r2=((c[2][3]*x2+c[2][2])*x2+c[2][1])*x2+c[2][0];
    const float r3=((c[3][3]*x2+c[3][2])*x2+c[3][1])*x2+c[3][0];
    return ((r3*x1+r2)*x1+r1)*x1+r0;
}
// Order: 1,y,y2,y3,x,xy,xy2,x2,x2y,x3.
inline float evaluate_total_cubic(const float c[10], float x1, float x2) {
    const float r0=((c[3]*x2+c[2])*x2+c[1])*x2+c[0];
    const float r1=(c[6]*x2+c[5])*x2+c[4];
    const float r2=c[8]*x2+c[7];
    return ((c[9]*x1+r2)*x1+r1)*x1+r0;
}
inline bool evaluate(float l1, float l2, Coefficients& out) {
    if (!std::isfinite(l1) || !std::isfinite(l2) || l1<kLowerLength || l1>kUpperLength || l2<kLowerLength || l2>kUpperLength) return false;
    const float center=0.5f*(kLowerLength+kUpperLength);
    const float inverse_half=1.0f/(0.5f*(kUpperLength-kLowerLength));
    float x1=(l1-center)*inverse_half, x2=(l2-center)*inverse_half;
    x1=x1 < -1.0f ? -1.0f : (x1 > 1.0f ? 1.0f : x1);
    x2=x2 < -1.0f ? -1.0f : (x2 > 1.0f ? 1.0f : x2);
    for (unsigned n=0; n<42; ++n) out.gamma[n]=evaluate_gamma(kGammaCoefficients[n], x1, x2);
    for (unsigned i=0; i<6; ++i) {
        const float weight=kStepEndpointWeight[i]; out.step_poles[i]=kStepPoles[i]; out.step_input_gain[i]=kStepInputGain[i];
        for (unsigned j=0; j<2; ++j) { const unsigned n=i*7+j; out.position_gain[n]=0.0f; out.step_position_gain[n]=0.0f; }
        for (unsigned j=2; j<7; ++j) { const unsigned n=i*7+j; out.position_gain[n]=evaluate_total_cubic(kPositionGainCoefficients[i*5+j-2], x1, x2); out.step_position_gain[n]=weight*out.position_gain[n]; }
        for (unsigned j=0; j<7; ++j) { const unsigned n=i*7+j;


            out.velocity_gain[n]=-kRates[i]*out.gamma[n];


            out.step_velocity_gain[n]=weight*out.velocity_gain[n];
        }
    }
    return true;
}
